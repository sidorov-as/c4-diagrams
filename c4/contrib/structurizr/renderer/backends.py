from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from abc import ABC, abstractmethod
from collections.abc import Mapping, Sequence
from pathlib import Path

from c4.constants import (
    DEFAULT_RENDERING_TIMEOUT_SECONDS,
    DEFAULT_STRUCTURIZR_BIN,
    RENDERING_TIMEOUT_SECONDS_ENV_VAR,
    STRUCTURIZR_BIN_ENV_VAR,
)
from c4.contrib.structurizr.renderer.errors import (
    StructurizrBackendConfigurationError,
    StructurizrRenderingError,
)
from c4.contrib.structurizr.renderer.options import StructurizrRenderOptions
from c4.enums import PNG, STRUCTURIZR_LOCAL_DIAGRAM_FORMATS, DiagramFormat
from c4.renderers.kroki import KrokiBackend
from c4.utils import MISSING, Maybe

_WORKSPACE_FILE_NAME = "workspace.dsl"
_LEGEND_SUFFIX = "-key"


class BaseStructurizrBackend(ABC):
    """
    Generate Structurizr diagrams from plain text.
    """

    @abstractmethod
    def to_bytes(
        self,
        workspace: str,
        *,
        format: DiagramFormat | str,
        render_options: StructurizrRenderOptions | None = None,
    ) -> bytes:
        """
        Export Structurizr DSL source and return generated bytes.

        Args:
            workspace: Structurizr DSL source to export.
            format: Target diagram format.
            render_options: Optional Structurizr renderer configuration.

        Returns:
            Structurizr DSL source as raw bytes.

        Raises:
            StructurizrRenderingError: If rendering fails.
        """
        raise NotImplementedError()  # pragma: no cover

    def to_file(
        self,
        workspace: str,
        output_path: str | Path,
        *,
        format: DiagramFormat | None,
        overwrite: bool = True,
        render_options: StructurizrRenderOptions | None = None,
    ) -> Path:
        """
        Export Structurizr DSL source and write generated bytes.

        Args:
            workspace: Structurizr DSL source to export.
            output_path: Destination file path.
            format: Target format; inferred from ``output_path`` when
                omitted.
            overwrite: Whether to replace an existing destination file.
            render_options: Optional Structurizr renderer configuration.

        Returns:
            Path to the written output file.

        Raises:
            ValueError: If ``format`` is ``None`` and the output path
                has no suffix.
            FileExistsError: If the output file exists
                and ``overwrite`` is ``False``.
            StructurizrRenderingError: If rendering fails.
        """
        output_path = Path(output_path)
        if format is None:
            if not output_path.suffix:
                raise ValueError(
                    "format is None and output_path has no extension."
                )
            format = output_path.suffix.lstrip(".").lower()  # type: ignore[assignment]

        if output_path.exists() and not overwrite:
            raise FileExistsError(
                f"Output file already exists: {output_path!s}"
            )

        content = self.to_bytes(
            workspace,
            format=format,  # type: ignore[arg-type]
            render_options=render_options,
        )
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_bytes(content)
        return output_path


class KrokiStructurizrBackend(BaseStructurizrBackend):
    """Generate Structurizr diagrams through a Kroki server."""

    def __init__(
        self,
        *,
        server_url: str | None = None,
        timeout_seconds: float = DEFAULT_RENDERING_TIMEOUT_SECONDS,
        use_post: bool = False,
        view_key: str | None = None,
        diagram_options: Mapping[str, str] | None = None,
        headers: Mapping[str, str] | None = None,
    ) -> None:
        """
        Initialize a Kroki-backed Structurizr exporter.

        Args:
            server_url: Optional Kroki server URL.
            timeout_seconds: Request timeout in seconds.
            use_post: Whether to use HTTP POST for Kroki requests.
            view_key: Optional Structurizr view key to render.
            diagram_options: Additional Kroki diagram options.
            headers: Additional HTTP request headers.
        """
        merged_options = dict(diagram_options or {})
        if view_key is not None:
            merged_options["view-key"] = view_key

        self._kroki = KrokiBackend(
            server_url=server_url,
            diagram_type="structurizr",
            timeout_seconds=timeout_seconds,
            use_post=use_post,
            diagram_options=merged_options,
            headers=headers,
        )

    def to_bytes(
        self,
        workspace: str,
        *,
        format: DiagramFormat | str = PNG,
        render_options: StructurizrRenderOptions | None = None,
    ) -> bytes:
        """Export a Structurizr workspace through Kroki.

        Args:
            workspace: Structurizr DSL source to export.
            format: Target diagram format.
            render_options: Reserved Structurizr renderer configuration.

        Returns:
            Rendered image content as raw bytes.

        Raises:
            StructurizrRenderingError: If rendering fails.
        """
        return self._kroki.to_bytes(workspace, format=format)


class LocalStructurizrBackend(BaseStructurizrBackend):
    """
    Export Structurizr views using the local ``structurizr`` CLI.

    ``structurizr export`` renders every view of a workspace in one run, one
    file per view (``<view-key>.png`` plus a ``<view-key>-key.png`` legend), so
    the backend picks the requested view from the output directory. PNG and
    SVG export needs Playwright Chromium (see the Structurizr CLI docs).

    Env vars:
      - STRUCTURIZR_BIN: executable name/path (default: 'structurizr')
    """

    def __init__(
        self,
        *,
        structurizr_bin: Maybe[str | Sequence[str]] = MISSING,
        timeout_seconds: Maybe[float] = MISSING,
        view_key: str | None = None,
        env: Mapping[str, str] | None = None,
    ) -> None:
        """
        Initialize the backend and check that the CLI is installed.

        Args:
            structurizr_bin: Executable name/path or a command prefix.
            timeout_seconds: Timeout of one CLI call.
            view_key: Key of the view to export. May be omitted when the
                workspace has exactly one view.
            env: Extra environment variables for the CLI process.

        Raises:
            StructurizrBackendConfigurationError: If the CLI is not found or
                the timeout is not a number.
        """
        self._env = dict(os.environ)
        if env:
            self._env.update(env)

        if structurizr_bin is MISSING:
            structurizr_bin = self._env.get(
                STRUCTURIZR_BIN_ENV_VAR, DEFAULT_STRUCTURIZR_BIN
            )
        self._command: list[str] = (
            [structurizr_bin]
            if isinstance(structurizr_bin, str)
            else [str(part) for part in structurizr_bin]
        )

        if timeout_seconds is MISSING:
            timeout_seconds = self._env.get(  # type: ignore[assignment]
                RENDERING_TIMEOUT_SECONDS_ENV_VAR,
                DEFAULT_RENDERING_TIMEOUT_SECONDS,
            )

        try:
            self._timeout_seconds = float(timeout_seconds)  # type: ignore[arg-type]
        except ValueError as exc:
            raise StructurizrBackendConfigurationError(
                f"Invalid timeout: {timeout_seconds!r} "
                f"(expected a number of seconds)."
            ) from exc

        self._view_key = view_key
        self._resolve_binary()

    def to_bytes(
        self,
        workspace: str,
        *,
        format: DiagramFormat | str = PNG,
        render_options: StructurizrRenderOptions | None = None,
    ) -> bytes:
        """
        Export one view of Structurizr DSL source to PNG or SVG.

        Args:
            workspace: Structurizr DSL source to export.
            format: ``'png'`` or ``'svg'``.
            render_options: Reserved Structurizr renderer configuration.

        Returns:
            Rendered image content as raw bytes.

        Raises:
            ValueError: If the format is not supported.
            StructurizrBackendConfigurationError: If the workspace has several
                views and no view key was given.
            StructurizrRenderingError: If the CLI fails or does not produce
                the requested view.
        """
        diagram_format = self._check_format(format)

        with tempfile.TemporaryDirectory(prefix="structurizr-gen-") as tmp:
            tmp_dir = Path(tmp)
            workspace_path = tmp_dir / _WORKSPACE_FILE_NAME
            output_dir = tmp_dir / "out"
            workspace_path.write_text(workspace, encoding="utf-8")

            cmd = [
                *self._command,
                "export",
                "-w",
                str(workspace_path),
                "-f",
                diagram_format.value,
                "-o",
                str(output_dir),
            ]
            try:
                res = subprocess.run(  # noqa: S603
                    cmd,
                    cwd=str(tmp_dir),
                    capture_output=True,
                    text=True,
                    timeout=self._timeout_seconds,
                    env=self._env,
                )
            except subprocess.TimeoutExpired as exc:
                raise StructurizrRenderingError(
                    f"Structurizr export timed out after "
                    f"{self._timeout_seconds:g} seconds."
                ) from exc

            # The CLI reports DSL errors in its log and still exits with 0,
            # so a missing output file is the reliable failure signal.
            output = "\n".join(
                part.strip() for part in (res.stderr, res.stdout) if part
            )
            if res.returncode != 0:
                raise StructurizrRenderingError(
                    output or "Structurizr export failed."
                )

            errors = "\n".join(
                line for line in output.splitlines() if " ERROR " in line
            )
            output_path = self._select_output(
                output_dir, diagram_format, errors
            )
            return output_path.read_bytes()

    def _select_output(
        self,
        output_dir: Path,
        diagram_format: DiagramFormat,
        errors: str,
    ) -> Path:
        suffix = f".{diagram_format.value}"
        exported = (
            sorted(
                path
                for path in output_dir.glob(f"*{suffix}")
                if not path.stem.endswith(_LEGEND_SUFFIX)
            )
            if output_dir.exists()
            else []
        )

        if self._view_key is not None:
            wanted = output_dir / f"{self._view_key}{suffix}"
            if wanted not in exported:
                hint = (
                    f" (available views: "
                    f"{', '.join(path.stem for path in exported)})"
                    if exported
                    else ""
                )
                raise StructurizrRenderingError(
                    f"View {self._view_key!r} was not exported{hint}."
                    + (f"\n{errors}" if errors else "")
                )
            return wanted

        if not exported:
            raise StructurizrRenderingError(
                "Structurizr export produced no views. Check that the "
                "workspace defines at least one view."
                + (f"\n{errors}" if errors else "")
            )

        if len(exported) > 1:
            available = ", ".join(path.stem for path in exported)
            raise StructurizrBackendConfigurationError(
                "The workspace has several views: pass view_key "
                f"(--structurizr-view-key) to choose one of: {available}."
            )
        return exported[0]

    @staticmethod
    def _check_format(format: DiagramFormat | str) -> DiagramFormat:
        try:
            diagram_format = DiagramFormat(format)
        except ValueError:
            diagram_format = None

        if diagram_format not in STRUCTURIZR_LOCAL_DIAGRAM_FORMATS:
            supported = ", ".join(
                sorted(item.value for item in STRUCTURIZR_LOCAL_DIAGRAM_FORMATS)
            )
            raise ValueError(
                f"Unsupported Structurizr local export format: {format!r}. "
                f"Supported formats: {supported}."
            )
        return diagram_format

    def _resolve_binary(self) -> None:
        if not self._command or not shutil.which(self._command[0]):
            raise StructurizrBackendConfigurationError(
                "Structurizr CLI is not available. "
                f"Tried {self._command[:1]!r} in PATH. "
                "Install it (https://docs.structurizr.com/cli), or configure "
                f"it with the {STRUCTURIZR_BIN_ENV_VAR} environment variable "
                "or structurizr_bin."
            )
